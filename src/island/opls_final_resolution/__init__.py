"""Final, corpus-scoped convention results, without inventing author authority.

Historical four-layer and J51 records are preserved. Backend implementation
resolution remains distinct from permanent absence of a source declaration.
"""

import json
from dataclasses import dataclass, field

from island.forcefields.opls_registry.api import require
from island.forcefields.selection.inventory import canonical, digest
from island.opls_conventions import LAYERS, signed
from island.opls_resolution import (
    REMAINING_SOURCE_GAPS,
    ConventionSources,
    use_convention_sources,
)
from island.opls_resolution import prepare_polymer_forcefield as _prepare

from .evidence import AUDIT_JSON

NINE_CONVENTIONS = REMAINING_SOURCE_GAPS
RESOLUTIONS = (
    "source_resolved",
    "converter_resolved",
    "backend_resolved",
    "derived_resolved",
    "conflicting",
    "unresolved_permanently",
)
# Generated by the independent offline reader; changing evidence requires a
# new version and review, not accepting an embedded self-reported checksum.
AUDIT_IDENTITY = "fd2cb7be5979c56b171fc99e3526f08326c4296bb118c2f0cd4096aa953de958"


def corpus_audit():
    value = json.loads(AUDIT_JSON)
    require(
        value.get("identity")
        == AUDIT_IDENTITY
        == digest({k: v for k, v in value.items() if k != "identity"}),
        "source_incompatible",
        "final_corpus_evidence_mutation",
    )
    return value


def _document(prior):
    audit = corpus_audit()
    historical = prior.payload
    require(
        [r["setting"] for r in audit["final_resolutions"]] == list(NINE_CONVENTIONS),
        "source_incompatible",
        "final_nine_inventory_mutation",
    )
    rows = []
    for result in audit["final_resolutions"]:
        old = next(r for r in historical["rows"] if r["setting"] == result["setting"])
        require(
            old["resolution"] == "unresolved" and old["value"] is None,
            "source_incompatible",
            "historical_source_authority_changed",
        )
        rows.append(
            signed(
                {
                    **{k: v for k, v in result.items() if k != "identity"},
                    "historical_resolution_identity": old["identity"],
                    "backend": old["backend"],
                    "units": old["units"],
                    "conversion_implementation": old["conversion_implementation"],
                    "backend_conversion_formula": old["conversion_formula"],
                }
            )
        )
    return signed(
        {
            "schema": "island.opls-final-convention-resolution.v1",
            "family": "opls",
            "selected_profile": historical["selected_profile"],
            "charge_origin": historical["charge_origin"],
            "domain": historical["domain"],
            "J51_resolution_identity": prior.identity,
            **{layer: historical[layer] for layer in LAYERS},
            "source_assets": historical["source_assets"],
            "source_audit_identity": audit["identity"],
            "source_corpus_identity": audit["corpus_identity"],
            "closure_scope": audit["closure_scope"],
            "nine_conventions": list(NINE_CONVENTIONS),
            "final_resolutions": rows,
            "unresolved_conventions": rows,
            "permanent_blockers": rows,
            "source_scope_review": historical["source_scope_review"],
            "execution_mode": historical["execution_mode"],
            "backend_policy": historical["backend_policy"],
            "research_MD_available": False,
            "default_MD_enabled": False,
            "production_candidate_available": False,
            "production_validated": False,
            "simulation_readiness": "not_established",
            "limitations": historical["limitations"],
        }
    )


@dataclass(frozen=True)
class FinalConventionPreparation:
    json_text: str
    prior: object = field(repr=False)

    @property
    def payload(self):
        return json.loads(self.json_text)

    @property
    def identity(self):
        return self.payload["identity"]

    @property
    def assignment(self):
        return self.prior.assignment

    @property
    def sources(self):
        return self.prior.sources

    def validate_integrity(self, system):
        assignment = self.prior.validate_integrity(system)
        require(
            self.json_text == canonical(_document(self.prior)),
            "source_incompatible",
            "mutated_final_convention_resolution",
        )
        return assignment

    def require_execution(self, system, action="static", *, research_opt_in=False):
        self.validate_integrity(system)
        if self.prior.prior.mode == "research_opt_in" and research_opt_in is True:
            require(
                False,
                "parameter_incomplete",
                "source_conventions_unresolved_permanently",
                missing=self.payload["permanent_blockers"],
                closure_scope=self.payload["closure_scope"],
                source_scope_review=self.payload["source_scope_review"],
            )
        return self.prior.require_execution(
            system, action, research_opt_in=research_opt_in
        )


def prepare_polymer_forcefield(system, forcefield="opls", **kwargs):
    """Ordinary callers select only the family; local assets are installed once."""
    prior = _prepare(system, forcefield=forcefield, **kwargs)
    return FinalConventionPreparation(canonical(_document(prior)), prior)


